USE InsuranceDb;
GO


IF OBJECT_ID('Buildings', 'U') IS NOT NULL DROP TABLE Buildings;
IF OBJECT_ID('BuildingTypes', 'U') IS NOT NULL DROP TABLE BuildingTypes;
IF OBJECT_ID('ClientIdentifier', 'U') IS NOT NULL DROP TABLE ClientIdentifier;
IF OBJECT_ID('Clients', 'U') IS NOT NULL DROP TABLE Clients;
IF OBJECT_ID('ClientTypes', 'U') IS NOT NULL DROP TABLE ClientTypes;
IF OBJECT_ID('Cities', 'U') IS NOT NULL DROP TABLE Cities;
IF OBJECT_ID('Counties', 'U') IS NOT NULL DROP TABLE Counties;
IF OBJECT_ID('Countries', 'U') IS NOT NULL DROP TABLE Countries;
GO


CREATE TABLE ClientTypes (
    Id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    Code NVARCHAR(20) NOT NULL,
    Name NVARCHAR(100) NOT NULL
);
GO


CREATE TABLE Countries (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Counties (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    CountryId UNIQUEIDENTIFIER NOT NULL,
    Name NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Cities (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    CountyId UNIQUEIDENTIFIER NOT NULL,
    Name NVARCHAR(100) NOT NULL,
    Code NVARCHAR(20) NOT NULL
);
GO


CREATE TABLE Clients (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    ClientTypeId INT NOT NULL,
    Name NVARCHAR(255) NOT NULL,
    Email NVARCHAR(100),
    Phone NVARCHAR(50),
    Address NVARCHAR(255),
    Cnp NVARCHAR(13),
    Cui NVARCHAR(10),
    CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME()
);
GO


CREATE TABLE BuildingTypes (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Name NVARCHAR(50) NOT NULL
);
GO

CREATE TABLE Buildings (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    ClientId UNIQUEIDENTIFIER NOT NULL,
    CityId UNIQUEIDENTIFIER NOT NULL,
    BuildingTypeId UNIQUEIDENTIFIER NOT NULL,
    Street NVARCHAR(255) NOT NULL,
    StreetNumber NVARCHAR(50) NOT NULL,
    ConstructionYear INT,
    NumberOfFloors INT,
    SurfaceArea DECIMAL(10,2) NOT NULL,
    InsuredValue DECIMAL(15,2) NOT NULL,
    FloodRisk BIT NOT NULL DEFAULT 0,
    EarthquakeRisk BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
