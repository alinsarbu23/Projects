CREATE TABLE ClientTypes (
    Id INT IDENTITY PRIMARY KEY,
    Code NVARCHAR(20) NOT NULL,
    Name NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Countries (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Counties (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    CountryId UNIQUEIDENTIFIER NOT NULL,
    Name NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Cities (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    CountyId UNIQUEIDENTIFIER NOT NULL,
    Name NVARCHAR(100) NOT NULL,
    Code NVARCHAR(20) NOT NULL
);
GO

CREATE TABLE Clients (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    ClientTypeId INT NOT NULL,
    Name NVARCHAR(255) NOT NULL,
    Email NVARCHAR(100),
    Phone NVARCHAR(50),
    Address NVARCHAR(255),
    Cnp NVARCHAR(13),
    Cui NVARCHAR(10),
    CreatedAt DATETIME2(0) DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2(0) DEFAULT SYSUTCDATETIME()
);
GO

CREATE TABLE BuildingTypes (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Name NVARCHAR(50) NOT NULL
);
GO

CREATE TABLE Buildings (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    ClientId UNIQUEIDENTIFIER NOT NULL,
    CityId UNIQUEIDENTIFIER NOT NULL,
    BuildingTypeId UNIQUEIDENTIFIER NOT NULL,
    Street NVARCHAR(255) NOT NULL,
    StreetNumber NVARCHAR(50) NOT NULL,
    ConstructionYear INT,
    NumberOfFloors INT,
    SurfaceArea DECIMAL(10,2) NOT NULL,
    InsuredValue DECIMAL(15,2) NOT NULL,
    FloodRisk BIT NOT NULL DEFAULT 0,
    EarthquakeRisk BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2(0) DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2(0) DEFAULT SYSUTCDATETIME()
);
GO

CREATE TABLE Administrators (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Name NVARCHAR(200) NOT NULL,
    Email NVARCHAR(100) NOT NULL,
    Role NVARCHAR(20) NOT NULL
);
GO

CREATE TABLE Brokers (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    BrokerCode NVARCHAR(50) NOT NULL,
    Name NVARCHAR(200) NOT NULL,
    Email NVARCHAR(100),
    Phone NVARCHAR(50),
    CommissionPercentage DECIMAL(5,2) NOT NULL,
    Status NVARCHAR(20) NOT NULL
);
GO

CREATE TABLE Currencies (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Code NVARCHAR(10) NOT NULL,
    Name NVARCHAR(50) NOT NULL,
    ExchangeRateToBase DECIMAL(10,4) NOT NULL,
    IsActive BIT NOT NULL
);
GO

CREATE TABLE FeeConfigurations (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Name NVARCHAR(200) NOT NULL,
    Type NVARCHAR(50) NOT NULL,
    Percentage DECIMAL(5,2) NOT NULL,
    AppliesToRisk NVARCHAR(20),
    IsActive BIT NOT NULL,
    EffectiveFrom DATE NOT NULL,
    EffectiveTo DATE
);
GO

CREATE TABLE RiskFactorConfigurations (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Level NVARCHAR(20) NOT NULL,
    ReferenceId UNIQUEIDENTIFIER NOT NULL,
    AdjustmentPercentage DECIMAL(5,2) NOT NULL,
    IsActive BIT NOT NULL
);
GO

CREATE TABLE Policies (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    PolicyNumber NVARCHAR(50) NOT NULL,
    BuildingId UNIQUEIDENTIFIER NOT NULL,
    BrokerId UNIQUEIDENTIFIER NOT NULL,
    CurrencyId UNIQUEIDENTIFIER NOT NULL,
    Status NVARCHAR(20) NOT NULL,
    StartDate DATE NOT NULL,
    EndDate DATE NOT NULL,
    BasePremium DECIMAL(15,2) NOT NULL,
    FinalPremium DECIMAL(15,2) NOT NULL,
    ActivatedAt DATETIME2,
    CancelledAt DATETIME2,
    CancellationReason NVARCHAR(255)
);
GO
